"""Generate the photo-estimated WOWROBO variant; run with the repository Python env."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET
import numpy as np
from scipy.spatial.transform import Rotation

D = Path(__file__).resolve().parents[1]
p = json.loads((D / 'wowrobo_camera_params.json').read_text())
name = 'so107_lab_soft_wowrobo'
s = (D / 'so107_lab_soft.urdf').read_text()
s = re.sub(r'<!-- so107_lab:.*?-->', '<!-- SO107 soft fingers with a photo-estimated WOWROBO camera mount.\n     Generated by tools/build_wowrobo_camera.py; edit wowrobo_camera_params.json.\n     See WOWROBO_CAMERA.md for estimation limits and coordinate conventions. -->', s, count=1, flags=re.S)
s = s.replace('<robot name="so107_lab_soft">', f'<robot name="{name}">')
foot = np.array(p['mount_surface_xyz_mm'], dtype=float)
center = foot + [0, 0, -p['plate_center_forward_mm']]
a = np.deg2rad(p['plate_tilt_toward_fingers_deg'])
# Camera height is derived from the measured neck, not the earlier rough lens-height estimate.
# Right-handed plate frame: x=robot -X, y=up, z=toward fingertips.
R = np.column_stack(([-1, 0, 0], [0, np.cos(a), -np.sin(a)], [0, -np.sin(a), -np.cos(a)]))
parts = []

def box(label, xyz, size, color, rot=np.eye(3)):
    parts.append((label, 'box', np.array(xyz), rot, np.array(size), color))

def platebox(label, xyz, size, color):
    box(label, center + R @ np.array(xyz), size, color, R)

def cylinder(label, xyz, radius, length, color):
    parts.append((label, 'cylinder', center + R @ np.array(xyz), R, np.array([radius, length]), color))

black = '0.10 0.11 0.12 1'
green = '0.10 0.19 0.13 1'
box('foot', foot + [0, p['foot_size_mm'][1]/2, 0], p['foot_size_mm'], black)
w, h = p['frame_outer_mm']; iw, ih = p['frame_opening_mm']; t = p['frame_thickness_mm']
assert w > iw > 0 and h > ih > 0 and t > 0
start = foot + [0, p['foot_size_mm'][1], -p['foot_size_mm'][2]/2]  # finger-facing edge of foot
bottom = center - R[:, 1] * h/2
horizontal_offset = bottom[2] - start[2]
assert p['neck_length_mm'] > abs(horizontal_offset), 'Neck too short for this forward offset'
center[1] = start[1] + np.sqrt(p['neck_length_mm']**2 - horizontal_offset**2) + R[1,1]*h/2
bottom = center - R[:, 1] * h/2
vec = bottom-start; length = np.linalg.norm(vec); along = vec/length
# Local Y follows the support; local X crosses the gripper.
neckR = np.column_stack(([1, 0, 0], along, np.cross([1, 0, 0], along)))
box('upright', (start+bottom)/2, [p['neck_width_mm'], length, p['neck_depth_mm']], black, neckR)
# Four rails preserve the visible rear opening.
for sign, label in [(-1, 'left'), (1, 'right')]:
    platebox('frame_'+label, [sign*(w+iw)/4, 0, 0], [(w-iw)/2, h, t], black)
for sign, label in [(-1, 'bottom'), (1, 'top')]:
    platebox('frame_'+label, [0, sign*(h+ih)/4, 0], [iw, (h-ih)/2, t], black)
pc = p['pcb_center_in_front_of_plate_mm']; pw, ph, pt = p['pcb_size_mm']
platebox('pcb', [0, 0, pc], [pw, ph, pt], green)
# Black sensor/lens base and cylindrical barrel.
lw, lh, lt = p['lens_base_size_mm']; basefront = pc + pt/2 + lt
platebox('lens_base', [0, 0, pc+pt/2+lt/2], [lw, lh, lt], black)
cylinder('lens_barrel', [0, 0, basefront+p['lens_length_mm']/2], p['lens_radius_mm'], p['lens_length_mm'], '0.035 0.04 0.045 1')
platebox('rear_connector', [0, -ih/2+3, -p['rear_connector_size_mm'][2]/2], p['rear_connector_size_mm'], '0.85 0.85 0.78 1')
for i, (x,y) in enumerate([(-pw/2+2,-ph/2+2),(-pw/2+2,ph/2-2),(pw/2-2,-ph/2+2),(pw/2-2,ph/2-2)]):
    cylinder('rear_screw_'+str(i), [x,y,-t/2-.7], 1.7, 1.4, '0.35 0.36 0.38 1')

def fmt(v):
    return ' '.join(f'{x:.9g}' for x in v)

blocks = ['<!-- WOWROBO mount approximation: dimensions and pose are photo estimates.\n       Collision primitives include the configurable per-surface padding. -->']
for label, kind, xyz, rot, size, color in parts:
    assert np.all(size > 0) and np.isclose(np.linalg.det(rot),1)
    rpy = Rotation.from_matrix(rot).as_euler('xyz')
    for tag in ['visual','collision']:
        pad = p['collision_padding_mm'] if tag=='collision' else 0
        if kind=='box':
            geom = f'<box size="{fmt((size+2*pad)/1000)}"/>'
        else:
            geom = f'<cylinder radius="{(size[0]+pad)/1000:.9g}" length="{(size[1]+2*pad)/1000:.9g}"/>'
        material = f'<material name="wowrobo_{label}"><color rgba="{color}"/></material>' if tag=='visual' else ''
        blocks.append(f'<{tag} name="wowrobo_{label}"><origin xyz="{fmt(xyz/1000)}" rpy="{fmt(rpy)}"/><geometry>{geom}</geometry>{material}</{tag}>')
s, n = re.subn(r'<!-- Wrist camera: the XLeRobot.*?(?=</link>)', '\n'.join(blocks)+'\n', s, count=1, flags=re.S)
assert n==1 and 'meshes/XLeRobot_camera' not in s
s = re.sub(r'<!-- Wrist camera frame \(dummy link\):.*?-->', '<!-- Estimated camera body frame: +X forward, +Y left, +Z up.\n     Origin is at the geometric lens-front center, not a calibrated optical center. -->', s, count=1, flags=re.S)
lensfront = center + R[:,2]*(basefront+p['lens_length_mm'])
bodyR = np.column_stack([R[:,2], R[:,0], R[:,1]])
origin = f'<origin xyz="{fmt(lensfront/1000)}" rpy="{fmt(Rotation.from_matrix(bodyR).as_euler("xyz"))}"/>'
s,n = re.subn(r'(<joint name="camera_joint" type="fixed">\s*)<origin[^>]+/>', lambda m:m[1]+origin, s, count=1); assert n==1
s=s.replace('</robot>', '''<!-- Optical axes: +Z forward, +X image-right, +Y image-down. -->
<link name="camera_optical_frame"/>
<joint name="camera_optical_joint" type="fixed">
  <parent link="camera_link"/><child link="camera_optical_frame"/>
  <origin xyz="0 0 0" rpy="-1.57079632679 0 -1.57079632679"/>
</joint>
</robot>''')
# The retained inertial was already approximate; avoid claiming it models the new bracket.
s = re.sub(r'<!-- Inertial = so101.*?-->', '<!-- Legacy approximate inertial retained; not updated for WOWROBO hardware.\n       This variant targets visualization and rigid collision checking, not dynamics. -->', s, count=1, flags=re.S)
(D / f'{name}.urdf').write_text(s)
srdf = ET.parse(D/'so107_lab_soft.srdf'); srdf.getroot().set('name',name)
ET.SubElement(srdf.getroot(),'disable_collisions',link1='camera_link',link2='camera_optical_frame',reason='Adjacent')
ET.indent(srdf);srdf.write(D/f'{name}.srdf',encoding='utf-8',xml_declaration=True)
print('Generated',name,'camera lens-front xyz (m)',lensfront/1000, 'primitives',len(parts))
